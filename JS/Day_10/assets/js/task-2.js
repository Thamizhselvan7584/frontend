// Explicit return

const add = (a, b) => {
    return a + b;
};

const square = (n) => {
    return n * n;
};

console.log(add(10, 20));
console.log(square(5));


// Implicit return

const addition = (a, b) => a + b;

const squareNumber = (n) => n * n;

console.log(addition(10, 20));
console.log(squareNumber(5));